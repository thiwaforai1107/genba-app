// 出退勤のデモ：今日と、過去20営業日ぶん
export function seedPunches() {
  const out = [];
  let n = 0;
  const add = (w, site, type, d, t, geo) => out.push({ id: `k${++n}`, w, site, type, at: at(d, t), geo });
  // 今日
  add('w1', 'N015', 'in', 0, '07:48', 85);
  add('w2', 'N015', 'in', 0, '07:55', 120);
  add('w3', 'N015', 'in', 0, '08:02', 64);
  // 過去
  const rainy = [-9, -16];
  let day = -1, count = 0;
  while (count < 20) {
    const d = new Date(); d.setDate(d.getDate() + day);
    const dow = d.getDay();
    if (dow !== 0) {
      count++;
      const site = day >= -6 ? 'N015' : day >= -20 ? 'N012' : 'N012';
      for (const w of ['w1', 'w2', 'w3']) {
        if (rainy.includes(day)) { add(w, site, 'rain', day, '07:30'); continue; }
        if (w === 'w3' && day === -11) continue; // 有休
        const s = (w.charCodeAt(1) * 7 + count * 13) % 15;
        const inT = `07:${String(40 + (s % 20)).padStart(2, '0')}`;
        const outH = 17 + ((s + count) % 3 === 0 ? 1 : 0);
        const outT = `${outH}:${String(5 + ((s * 3) % 50)).padStart(2, '0')}`;
        add(w, site, 'in', day, inT, 60 + s * 9);
        add(w, site, 'break', day, '12:00');
        add(w, site, 'back', day, '13:00');
        // 1件だけ退勤の打刻漏れ（アラートのデモ）
        if (!(w === 'w2' && day === -1)) add(w, site, 'out', day, outT);
      }
    }
    day--;
  }
  return out;
}

